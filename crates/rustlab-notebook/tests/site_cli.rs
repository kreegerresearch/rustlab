//! Site chrome through the real binary: `rustlab.toml` `[site]`,
//! `--header-html`, `--footer-html`, `--stylesheet`, on single-file and
//! directory renders and on a live `notebook watch` page (its CSP).
//!
//! `HOME` and `XDG_CONFIG_HOME` point at a temp dir so the developer's
//! own rc file never leaks in.

use std::io::{Read, Write};
use std::net::TcpStream;
use std::path::Path;
use std::process::{Command, Output, Stdio};
use std::time::{Duration, Instant};

use tempfile::TempDir;

const BIN: &str = env!("CARGO_BIN_EXE_rustlab-notebook");

const SITE: &str = r##"
[site]
brand = { label = "Kreeger Labs", href = "https://kreegerlabs.com/" }
nav = [
  { label = "Notebooks", href = "/notebooks/" },
  { label = "About & <contact>", href = "about.html" },
]
footer = "© 2026 Kreeger Labs"
stylesheets = ["https://kreegerlabs.com/css/site.css"]
"##;

const NB: &str = "# Filters\n\nSome text.\n";

fn cmd(home: &Path, dir: &Path) -> Command {
    let mut c = Command::new(BIN);
    c.current_dir(dir)
        .env("HOME", home)
        .env("XDG_CONFIG_HOME", home.join(".config"))
        .env("CI", "1")
        .env_remove("RUSTLAB_VIEWER_SOCK");
    c
}

fn run(home: &Path, dir: &Path, args: &[&str]) -> Output {
    cmd(home, dir).args(args).output().unwrap()
}

fn text(o: &Output) -> String {
    format!(
        "status {:?}\nstdout:\n{}\nstderr:\n{}",
        o.status.code(),
        String::from_utf8_lossy(&o.stdout),
        String::from_utf8_lossy(&o.stderr)
    )
}

fn project(site: &str) -> TempDir {
    let p = TempDir::new().unwrap();
    std::fs::write(p.path().join("rustlab.toml"), site).unwrap();
    std::fs::create_dir_all(p.path().join("notes/ch2")).unwrap();
    std::fs::write(p.path().join("notes/filters.md"), NB).unwrap();
    std::fs::write(p.path().join("notes/ch2/windows.md"), "# Windows\n").unwrap();
    std::fs::write(
        p.path().join("notes/hdr.html"),
        "<div id=\"brand-bar\">KL</div>",
    )
    .unwrap();
    std::fs::write(p.path().join("notes/ftr.html"), "<p id=\"legal\">Legal</p>").unwrap();
    p
}

#[test]
fn render_single_file_with_site_config_and_fragments() {
    let home = TempDir::new().unwrap();
    let p = project(SITE);
    let o = run(
        home.path(),
        p.path(),
        &[
            "render",
            "notes/filters.md",
            "-o",
            "out/filters.html",
            "--header-html",
            "notes/hdr.html",
            "--footer-html",
            "notes/ftr.html",
        ],
    );
    assert!(o.status.success(), "{}", text(&o));
    let html = std::fs::read_to_string(p.path().join("out/filters.html")).unwrap();
    assert!(html
        .contains("<a class=\"rl-site-brand\" href=\"https://kreegerlabs.com/\">Kreeger Labs</a>"));
    assert!(html.contains("<a href=\"about.html\">About &amp; &lt;contact&gt;</a>"));
    assert!(html.contains("<footer>© 2026 Kreeger Labs</footer>"));
    assert!(
        html.contains("<link rel=\"stylesheet\" href=\"https://kreegerlabs.com/css/site.css\">")
    );
    assert!(html.contains("<div class=\"rl-site-header\"><div id=\"brand-bar\">KL</div></div>"));
    assert!(html.contains("<div class=\"rl-site-footer\"><p id=\"legal\">Legal</p></div>\n</main>"));
    assert!(!html.contains("Generated by rustlab-notebook"));
}

#[test]
fn cli_stylesheet_overrides_toml_and_empty_footer_removes_it() {
    let home = TempDir::new().unwrap();
    let p = project("[site]\nfooter = \"\"\nstylesheets = [\"/toml.css\"]\n");
    let o = run(
        home.path(),
        p.path(),
        &[
            "render",
            "notes/filters.md",
            "-o",
            "out/f.html",
            "--stylesheet",
            "https://cdn.example/a.css",
            "--stylesheet",
            "b.css",
        ],
    );
    assert!(o.status.success(), "{}", text(&o));
    let html = std::fs::read_to_string(p.path().join("out/f.html")).unwrap();
    assert!(html.contains("<link rel=\"stylesheet\" href=\"https://cdn.example/a.css\">"));
    assert!(html.contains("<link rel=\"stylesheet\" href=\"b.css\">"));
    assert!(!html.contains("toml.css"));
    assert!(!html.contains("<footer"));
}

#[test]
fn javascript_hrefs_are_refused_before_anything_is_written() {
    let home = TempDir::new().unwrap();
    let p = project("[site]\nbrand = { label = \"x\", href = \"javascript:alert(1)\" }\n");
    let o = run(
        home.path(),
        p.path(),
        &["render", "notes/filters.md", "-o", "out/x.html"],
    );
    assert_eq!(o.status.code(), Some(2), "{}", text(&o));
    let err = String::from_utf8_lossy(&o.stderr);
    assert!(err.contains("site.brand.href"), "{err}");
    assert!(!p.path().join("out/x.html").exists());

    let p = project("");
    let o = run(
        home.path(),
        p.path(),
        &[
            "render",
            "notes/filters.md",
            "-o",
            "out/x.html",
            "--stylesheet",
            "javascript:alert(1)",
        ],
    );
    assert_eq!(o.status.code(), Some(2), "{}", text(&o));
    assert!(String::from_utf8_lossy(&o.stderr).contains("--stylesheet"));
    assert!(!p.path().join("out/x.html").exists());
}

#[test]
fn fragments_outside_the_jail_are_refused() {
    let home = TempDir::new().unwrap();
    let p = project("");
    std::fs::write(p.path().join("outside.html"), "<b>x</b>").unwrap();
    let o = run(
        home.path(),
        p.path(),
        &[
            "render",
            "notes/filters.md",
            "-o",
            "out/x.html",
            "--header-html",
            "outside.html",
        ],
    );
    assert_eq!(o.status.code(), Some(2), "{}", text(&o));
    assert!(
        String::from_utf8_lossy(&o.stderr).contains("path escapes"),
        "{}",
        text(&o)
    );
    // --jail-root widens it.
    let o = run(
        home.path(),
        p.path(),
        &[
            "render",
            "notes/filters.md",
            "-o",
            "out/x.html",
            "--header-html",
            "outside.html",
            "--jail-root",
            ".",
        ],
    );
    assert!(o.status.success(), "{}", text(&o));
}

