#[test]
fn directory_render_rebases_relative_hrefs_and_themes_the_index() {
    let home = TempDir::new().unwrap();
    let p = project(SITE);
    let o = run(home.path(), p.path(), &["render", "notes", "-o", "site"]);
    assert!(o.status.success(), "{}", text(&o));
    let nested = std::fs::read_to_string(p.path().join("site/ch2/windows.html")).unwrap();
    assert!(
        nested.contains("<a href=\"../about.html\">"),
        "nested page rebases"
    );
    assert!(nested.contains("<a href=\"/notebooks/\">Notebooks</a>"));
    assert!(nested.contains("class=\"prev\"") || nested.contains("class=\"next\""));
    let index = std::fs::read_to_string(p.path().join("site/index.html")).unwrap();
    assert!(index.contains("rl-site-brand"));
    assert!(index.contains("<footer>© 2026 Kreeger Labs</footer>"));
}

fn http_get(port: u16, path: &str) -> Option<String> {
    let mut s = TcpStream::connect(("127.0.0.1", port)).ok()?;
    s.set_read_timeout(Some(Duration::from_secs(10))).ok()?;
    write!(
        s,
        "GET {path} HTTP/1.1\r\nHost: 127.0.0.1:{port}\r\nConnection: close\r\n\r\n"
    )
    .ok()?;
    let mut buf = String::new();
    s.read_to_string(&mut buf).ok()?;
    Some(buf)
}

struct Child(std::process::Child);
impl Drop for Child {
    fn drop(&mut self) {
        let _ = self.0.kill();
        let _ = self.0.wait();
    }
}

#[test]
fn watch_page_carries_the_chrome_and_widens_only_style_src() {
    let home = TempDir::new().unwrap();
    let p = project(SITE);
    let port = std::net::TcpListener::bind("127.0.0.1:0")
        .unwrap()
        .local_addr()
        .unwrap()
        .port();
    let port_s = port.to_string();
    let _child = Child(
        cmd(home.path(), p.path())
            .args([
                "watch",
                "notes/filters.md",
                "--no-browser",
                "--port",
                &port_s,
                "--stylesheet",
                "https://kreegerlabs.com/css/site.css",
                "--stylesheet",
                "https://fonts.example.net/x.css",
            ])
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .spawn()
            .unwrap(),
    );
    let deadline = Instant::now() + Duration::from_secs(60);
    let page = loop {
        if let Some(body) = http_get(port, "/n/filters") {
            if body.starts_with("HTTP/1.1 200") {
                break body;
            }
        }
        assert!(Instant::now() < deadline, "watch server did not answer");
        std::thread::sleep(Duration::from_millis(200));
    };
    let csp = page
        .lines()
        .find(|l| {
            l.to_ascii_lowercase()
                .starts_with("content-security-policy:")
        })
        .expect("csp header")
        .to_string();
    assert!(
        csp.contains(
            "style-src 'self' 'unsafe-inline' https://kreegerlabs.com https://fonts.example.net;"
        ),
        "{csp}"
    );
    assert!(csp.contains("font-src 'self';"), "{csp}");
    assert!(csp.contains("img-src 'self' data: blob:;"), "{csp}");
    assert!(page.contains("rl-site-brand"));
    assert!(page.contains("<footer>© 2026 Kreeger Labs</footer>"));
    assert!(page.contains("<link rel=\"stylesheet\" href=\"https://fonts.example.net/x.css\">"));
}
